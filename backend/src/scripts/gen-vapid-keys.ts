// Rotating the keypair invalidates every existing push subscription.

import { generateVAPIDKeys } from 'web-push';

const { publicKey, privateKey } = generateVAPIDKeys();

console.log(`# VAPID keypair for Web Push — generated by \`bun run vapid:gen\`.
# Paste these into backend/.env. Keep VAPID_PRIVATE_KEY secret — it never leaves the server.
# Set VAPID_SUBJECT to a mailto: or https: contact the push service can reach.
VAPID_PUBLIC_KEY=${publicKey}
VAPID_PRIVATE_KEY=${privateKey}
VAPID_SUBJECT=mailto:you@example.com`);
