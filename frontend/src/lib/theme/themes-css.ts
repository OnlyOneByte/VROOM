import { oklchToHex } from './oklch-to-hex';
import type { ThemeDefinition, ThemeTokens } from './theme-types';

const GENERATED_HEADER = `/* GENERATED by themes-css.ts. DO NOT EDIT BY HAND — regenerate from THEME_REGISTRY. */`;

function declarations(tokens: ThemeTokens): string {
	return Object.keys(tokens)
		.sort()
		.map(key => `  --${key}: ${tokens[key as keyof ThemeTokens]};`)
		.join('\n');
}

export function themeBlocks(theme: ThemeDefinition): string {
	const sel = `:root[data-theme="${theme.id}"]`;
	return (
		`${sel} {\n${declarations(theme.light)}\n}\n\n` +
		`${sel}.dark {\n${declarations(theme.dark)}\n}`
	);
}

export function generateThemesCss(
	registry: Record<string, ThemeDefinition>,
	defaultThemeId = 'default'
): string {
	const nonDefault = Object.values(registry)
		.filter(t => t.id !== defaultThemeId)
		.sort((a, b) => a.id.localeCompare(b.id));

	if (nonDefault.length === 0) {
		return `${GENERATED_HEADER}\n/* No non-default themes registered yet — default is served by app.css's bare :root/.dark. */\n`;
	}
	return `${GENERATED_HEADER}\n\n${nonDefault.map(themeBlocks).join('\n\n')}\n`;
}

export function nonDefaultThemeIds(
	registry: Record<string, ThemeDefinition>,
	defaultThemeId = 'default'
): string[] {
	return Object.values(registry)
		.filter(t => t.id !== defaultThemeId)
		.map(t => t.id)
		.sort();
}

function backgroundHex(theme: ThemeDefinition, variant: 'light' | 'dark'): string {
	const hex = oklchToHex(theme[variant].background);
	if (!hex) throw new Error(`${theme.id}.${variant}.background is not a parseable oklch() color`);
	return hex;
}

function objectKey(id: string): string {
	return /^[A-Za-z_$][\w$]*$/.test(id) ? id : `'${id}'`;
}

// Emitted already Prettier-formatted, so formatting the file cannot break the byte-equality test.
export function generateThemeChromeModule(
	registry: Record<string, ThemeDefinition>,
	defaultThemeId: string
): string {
	const rows = Object.values(registry)
		.sort((a, b) => a.id.localeCompare(b.id))
		.map(
			t =>
				`\t${objectKey(t.id)}: { light: '${backgroundHex(t, 'light')}', dark: '${backgroundHex(t, 'dark')}' }`
		);
	return [
		'// GENERATED by themes-css.ts. DO NOT EDIT BY HAND — regenerate from THEME_REGISTRY.',
		'',
		`export const DEFAULT_THEME_ID = '${defaultThemeId}';`,
		'',
		'export const THEME_BACKGROUND_HEX: Record<string, { light: string; dark: string }> = {',
		rows.join(',\n'),
		'};',
		''
	].join('\n');
}
